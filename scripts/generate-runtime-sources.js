const fs = require('fs')
const path = require('path')
const ts = require('typescript')

// The html font-size watcher and the css transformer are written once, as real functions (src/runtime), and run directly
// in the bundle. getUiScalerSsrScript() needs the same code as a string, so it is compiled here, at build time, into plain
// ES2015 and written to src/generated. That way it never depends on how a consumer's bundler transforms this package.
const runtimeDir = path.join(__dirname, '..', 'src', 'runtime')
const outDir = path.join(__dirname, '..', 'src', 'generated')

const sources = {
  fontSizeHandlerSource: 'fontSizeHandler.ts',
  stylesTransformerSource: 'stylesTransformer.ts'
}

const lines = ['// Generated by scripts/generate-runtime-sources.js. Do not edit.']

for (const [exportName, fileName] of Object.entries(sources)) {
  const input = fs.readFileSync(path.join(runtimeDir, fileName), 'utf8')
  const { outputText } = ts.transpileModule(input, {
    compilerOptions: { target: ts.ScriptTarget.ES2015, module: ts.ModuleKind.ESNext, removeComments: true }
  })
  const functionSource = outputText.trim().replace(/^export function /, 'function ')
  if (!/^function \w+\(params\) \{[\s\S]*\}$/.test(functionSource) || /^(import|export) /m.test(functionSource)) {
    throw new Error(`${fileName} must contain a single self-contained exported function`)
  }
  lines.push(`export const ${exportName} = ${JSON.stringify(functionSource)}`)
}

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(path.join(outDir, 'runtimeSsrSources.ts'), lines.join('\n') + '\n')
